const router = require('express').Router();
const controller = require('../controllers/webController');
const { requireAuth, requireVerified } = require('../middleware/auth');
const settingsController = require('../controllers/settingsController');
const communityController = require('../controllers/communityController');
const { postUpload, profileUpload, validatePostUpload, validateProfileUpload, handleUploadError } = require('../middleware/uploads');

router.get('/', controller.home);
router.get('/dashboard', requireAuth, requireVerified, controller.dashboard);
router.get('/explore', requireAuth, requireVerified, communityController.explore);
router.get('/communities/:slug', requireAuth, requireVerified, communityController.detail);
router.post('/posts', requireAuth, requireVerified, postUpload, handleUploadError, validatePostUpload, controller.createPost);
router.post('/communities', requireAuth, requireVerified, controller.createCommunity);
router.post('/communities/:id/join', requireAuth, requireVerified, controller.joinCommunity);
router.post('/users/:id/follow', requireAuth, requireVerified, controller.followUser);
router.get('/communities/:id/manage', requireAuth, requireVerified, communityController.ownerOnly, communityController.manage);
router.post('/communities/:id/manage', requireAuth, requireVerified, communityController.ownerOnly, communityController.update);
router.post('/communities/:id/members/:memberId/remove', requireAuth, requireVerified, communityController.ownerOnly, communityController.removeMember);
router.post('/communities/:id/requests/:userId', requireAuth, requireVerified, communityController.moderationOnly, communityController.reviewRequest);
router.post('/communities/:id/members/:userId/role', requireAuth, requireVerified, communityController.ownerOnly, communityController.setModerator);
router.get('/settings/:section?', requireAuth, requireVerified, settingsController.page);
router.post('/settings/profile', requireAuth, requireVerified, profileUpload, handleUploadError, validateProfileUpload, settingsController.updateProfile);
router.post('/settings/security/password', requireAuth, requireVerified, settingsController.changePassword);
router.post('/settings/security/devices/:id/logout', requireAuth, requireVerified, settingsController.logoutDevice);
router.post('/settings/security/devices/logout-all', requireAuth, requireVerified, settingsController.logoutAll);
router.post('/settings/privacy', requireAuth, requireVerified, settingsController.setInactivity);
router.get('/settings/account/download', requireAuth, requireVerified, settingsController.downloadData);
router.post('/settings/account/delete', requireAuth, requireVerified, settingsController.deleteAccount);
['/about', '/about/developer', '/privacy', '/terms', '/community-guidelines', '/accessibility', '/contact'].forEach((path) => router.get(path, controller.infoPage));
router.get('/robots.txt', controller.robots);
router.get('/sitemap.xml', controller.sitemap);

module.exports = router;
